    fun parse(s: String): Array<DoubleArray> =
        s.trim().split(" ").map { p -> val q = p.split(","); doubleArrayOf(q[0].toDouble(), q[1].toDouble()) }.toTypedArray()

    fun inside(poly: Array<DoubleArray>, x: Double, y: Double): Boolean {
        var c = false; var j = poly.size - 1
        for (i in poly.indices) {
            val xi = poly[i][0]; val yi = poly[i][1]; val xj = poly[j][0]; val yj = poly[j][1]
            if ((yi > y) != (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c
            j = i
        }
        return c
    }

    fun buildMask(w: Int, h: Int): BooleanArray {
        val land = LAND.map { parse(it) }; val water = WATER.map { parse(it) }
        val m = BooleanArray(w * h)
        for (y in 0 until h) {
            val lat = 90.0 - (y + 0.5) * 180.0 / h
            for (x in 0 until w) {
                val lon = -180.0 + (x + 0.5) * 360.0 / w
                var on = false
                for (p in land) if (inside(p, lon, lat)) { on = true; break }
                if (on) for (p in water) if (inside(p, lon, lat)) { on = false; break }
                m[y * w + x] = on
            }
        }
        return m
    }
